    static func isPrivateBrowserWindow(bundleIdentifier:String?,title:String?)->Bool {
        guard let bundleIdentifier,let title else{return false}
        let indicators:[String]
        if bundleIdentifier.hasPrefix("com.brave.Browser"){indicators=braveTitles}
        else if bundleIdentifier.hasPrefix("com.microsoft.edgemac"){return title.contains("InPrivate")}
        else if chromiumPrefixes.contains(where:bundleIdentifier.hasPrefix){indicators=chromiumTitles}
        else if bundleIdentifier=="com.apple.Safari" || bundleIdentifier=="com.apple.SafariTechnologyPreview"{indicators=safariTitles}
        else if firefoxPrefixes.contains(where:bundleIdentifier.hasPrefix){indicators=firefoxTitles}
        else if bundleIdentifier=="com.duckduckgo.macos.browser"{return title.contains("Fire Window")}
        else{return false}
        return indicators.contains(where:title.contains)
    }
